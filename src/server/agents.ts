/**
 * Helper to compute precise Kenyan statutory payroll items according to Kenyan laws
 */
export interface KenyanPayslipCalculation {
  gross: number;
  basic: number;
  houseAllowance: number;
  transportAllowance: number;
  nssf: number;
  shif: number; // NHIF / SHIF (2.75%)
  housingLevy: number; // Affordable Housing Levy (1.5%)
  taxableSalary: number;
  paye: number;
  personalRelief: number;
  insuranceRelief: number;
  totalDeductions: number;
  netPay: number;
}

export function calculateKenyanPayroll(gross: number): KenyanPayslipCalculation {
  const basic = Math.round(gross * 0.70);
  const houseAllowance = Math.round(gross * 0.20);
  const transportAllowance = Math.round(gross * 0.10);

  // 1. NSSF: New Tier Scheme. Emp rate is 6%, capped at KES 2,160 for salaries above KES 36,000
  const nssf = 2160;

  // 2. Affordable Housing Levy (AHL): 1.5% of gross
  const housingLevy = Math.round(gross * 0.015);

  // 3. Social Health Insurance Fund (SHIF): 2.75% of gross
  const shif = Math.round(gross * 0.0275);

  // 4. Taxable salary = Gross - NSSF (NSSF contribution is tax exempt in Kenya)
  const taxableSalary = Math.max(0, gross - nssf);

  // 5. Progressive PAYE Rates (Finance Act 2023):
  // - First KES 24,000 @ 10%
  // - Next KES 8,333 @ 25%
  // - Above KES 32,333 @ 30% (since 145k-175k is in this bracket)
  let rawTax = 0;
  if (taxableSalary <= 24000) {
    rawTax = taxableSalary * 0.10;
  } else if (taxableSalary <= 32333) {
    rawTax = (24000 * 0.10) + ((taxableSalary - 24000) * 0.25);
  } else {
    rawTax = (24000 * 0.10) + (8333 * 0.25) + ((taxableSalary - 32333) * 0.30);
  }

  // Personal Tax Relief: KES 2,400 monthly relief
  const personalRelief = 2400;

  // Insurance Relief: 15% of AHL + 15% of SHIF (NHIF)
  const insuranceRelief = Math.round((housingLevy + shif) * 0.15);

  // Total Net PAYE Tax Payable
  let paye = Math.round(rawTax - personalRelief - insuranceRelief);
  if (paye < 0) paye = 0;

  const totalDeductions = nssf + housingLevy + shif + paye;
  const netPay = gross - totalDeductions;

  return {
    gross,
    basic,
    houseAllowance,
    transportAllowance,
    nssf,
    shif,
    housingLevy,
    taxableSalary,
    paye,
    personalRelief,
    insuranceRelief,
    totalDeductions,
    netPay
  };
}

