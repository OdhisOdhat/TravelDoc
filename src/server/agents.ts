// Setup the Gemini client
const getGeminiClient = (): GoogleGenAI => {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    throw new Error("GEMINI_API_KEY is not set in environment variables");
  }
  return new GoogleGenAI({
    apiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      }
    }
  });
};

/**
 * Agent 1: Candidate Processing Agent
 * Validates, cleans, and structures candidate info, mapping them to event roles. Also enrich missing corporate info.
 */
export async function runCandidateProcessor(
  ai: GoogleGenAI,
  candidates: Candidate[],
  event: EventDetails
): Promise<{ candidates: Candidate[]; logs: AgentLog[] }> {
  const logs: AgentLog[] = [];
  const timestamp = new Date().toISOString();

  logs.push({
    id: `log-c1`,
    timestamp,
    agent: 'Candidate Processor',
    level: 'info',
    message: `Starting extraction and validation for ${candidates.length} traveler(s).`,
    details: `Initiating mapping against event: "${event.name}" hosted by "${event.hostOrg}".`
  });

  const processedCandidates: Candidate[] = [];

  candidates.forEach((cand, idx) => {
    // Autogenerate corporate details if missing
    if (!cand.organization || cand.organization.trim() === '') {
      const mockEmp = KENYAN_EMPLOYERS[idx % KENYAN_EMPLOYERS.length];
      cand.organization = mockEmp.name;
      cand.kraPin = cand.kraPin || mockEmp.pin;
      cand.phone = cand.phone || mockEmp.phone;
      cand.companyAddress = cand.companyAddress || mockEmp.address;
      cand.companyEmail = cand.companyEmail || mockEmp.email;
      
      logs.push({
        id: `log-enrich-${cand.id}`,
        timestamp: new Date().toISOString(),
        agent: 'Candidate Processor',
        level: 'info',
        message: `Autogenerated corporate details for nominee: ${cand.fullName || 'Participant'}`,
        details: `Assigned Company: "${mockEmp.name}", KRA PIN: "${mockEmp.pin}", Phone: "${mockEmp.phone}"`
      });
    }
  });

  for (const candidate of candidates) {
    // Basic verification and data enrichment with Gemini
    const prompt = `Validate the traveler profile for the event "${event.name}". 
    Input candidate profile: ${JSON.stringify(candidate)}
    
    You must maintain the exact passportNumber (${candidate.passportNumber}) and fullName (${candidate.fullName}) from the input profile. Do not alter or omit them.
    If any of the travel dates are missing or inconsistent (e.g. landing after event starts or long stay), flag them or output safe standard dates.
    Enrich the details. Generate a concise paragraph of custom travel details or special notes for this traveler if none is provided.
    Ensure to return structured data matching the schema.`;

    try {
      const response = await ai.models.generateContent({
        model: "gemini-3.5-flash",
        contents: prompt,
        config: {
          responseMimeType: "application/json",
          responseSchema: {
            type: Type.OBJECT,
            properties: {
              fullName: { type: Type.STRING },
              passportNumber: { type: Type.STRING },
              jobTitle: { type: Type.STRING },
              department: { type: Type.STRING },
              monthlySalary: { type: Type.NUMBER },
              hireDate: { type: Type.STRING },
              roleInEvent: { type: Type.STRING, description: "One of: Speaker, Attendee, Exhibitor, VIP Guest" },
              travelStartDate: { type: Type.STRING },
              travelEndDate: { type: Type.STRING },
              email: { type: Type.STRING },
              customDetails: { type: Type.STRING, description: "A tailored travel purpose or profile note." }
            },
            required: ["fullName", "passportNumber", "jobTitle", "department", "monthlySalary", "hireDate", "roleInEvent", "travelStartDate", "travelEndDate", "email", "customDetails"]
          }
        }
      });

      const resultText = response.text || "{}";
      const cleanedJson = JSON.parse(resultText);

      processedCandidates.push({
        ...candidate,
        fullName: candidate.fullName || cleanedJson.fullName,
        passportNumber: (candidate.passportNumber && candidate.passportNumber !== 'PENDING') ? candidate.passportNumber : (cleanedJson.passportNumber || candidate.passportNumber),
        jobTitle: cleanedJson.jobTitle || candidate.jobTitle,
        department: cleanedJson.department || candidate.department,
        monthlySalary: candidate.monthlySalary || cleanedJson.monthlySalary || 145000,
        hireDate: cleanedJson.hireDate || candidate.hireDate,
        roleInEvent: cleanedJson.roleInEvent || candidate.roleInEvent,
        travelStartDate: cleanedJson.travelStartDate || candidate.travelStartDate,
        travelEndDate: cleanedJson.travelEndDate || candidate.travelEndDate,
        customDetails: cleanedJson.customDetails || candidate.customDetails || "No custom traveler notes."
      });

      logs.push({
        id: `log-c-${candidate.id}`,
        timestamp: new Date().toISOString(),
        agent: 'Candidate Processor',
        level: 'success',
        message: `Successfully validated candidate: ${candidate.fullName}`,
        details: `Assigned event role: ${cleanedJson.roleInEvent}. Verified department: ${cleanedJson.department}. Passport status: OK.`
      });
    } catch (err: any) {
      logs.push({
        id: `err-c-${candidate.id}`,
        timestamp: new Date().toISOString(),
        agent: 'Candidate Processor',
        level: 'warning',
        message: `Candidate ${candidate.fullName} validation completed with local fallback.`,
        details: `API call noticed: ${err.message || err}. Using original fields safely.`
      });
      processedCandidates.push(candidate);
    }
  }

  return { candidates: processedCandidates, logs };
}

/**
 * Agent 2: Corporate Branding Agent & Agent 6: Design and Layout Agent
 * Generates brand colors, SVG logo designs, and typography guidelines.
 */
export async function runCorporateBranding(
  ai: GoogleGenAI,
  company: CompanyProfile,
  themePreference: DesignTheme
): Promise<{ branding: BrandingDetails; logs: AgentLog[] }> {
  const logs: AgentLog[] = [];
  const timestamp = new Date().toISOString();

  logs.push({
    id: `log-b1`,
    timestamp,
    agent: 'Corporate Branding',
    level: 'info',
    message: `Designing a custom brand corporate identity for "${company.name}" under theme style "${themePreference}".`,
    details: `Company operates in industry: "${company.industry}". Custom logo descriptor: "${company.logoPrompt || 'Corporate emblem'}".`
  });

  const prompt = `Design a premium corporate visual brand identity for a company named "${company.name}" in the "${company.industry}" industry.
  Theme Preference: ${themePreference}.
  Custom Logo Prompt: ${company.logoPrompt || "A clean, executive corporate mark"}.

  Tasks:
  1. Select a professional cohesive color palette:
     - Primary hex color (e.g. deep navy, emerald, sophisticated charcoal, etc.)
     - Secondary hex color (e.g. slate, gold accent, warm beige, soft teal)
  2. Choose premium typography:
     - Font Heading (e.g., Space Grotesk, Playfair Display, Inter, Outfit)
     - Font Body (e.g., Inter, JetBrains Mono, Lora)
  3. Create an executive and professional SVG logo design representation.
     - Respond MUST contain a single field 'logoSvg' containing valid complete inline SVG source code (DO NOT wrap in markdown, no \`\`\`xml, keep it clean).
     - The SVG must be self-contained: width="160" height="48" viewBox="0 0 160 48" fill="none".
     - Draw elegant professional paths, circles, grids, or lines that dynamically represent the company name "${company.name}" and the primary/secondary colors you selected.
  4. Select a suitable letterhead physical layout style ('Minimal Header', 'Side Accent Bar', 'Top Gradient Banner', 'Classic Crest').

  Returns a clean strict JSON matching the schema properties.`;

  try {
    const response = await ai.models.generateContent({
      model: "gemini-3.5-flash",
      contents: prompt,
      config: {
        responseMimeType: "application/json",
        responseSchema: {
          type: Type.OBJECT,
          properties: {
            primaryColor: { type: Type.STRING },
            secondaryColor: { type: Type.STRING },
            fontHeading: { type: Type.STRING },
            fontBody: { type: Type.STRING },
            letterheadStyle: { type: Type.STRING, description: "One of: Minimal Header, Side Accent Bar, Top Gradient Banner, Classic Crest" },
            logoSvg: { type: Type.STRING, description: "A valid complete self-contained SVG string which renders a sleek corporate logo mark and name text. Incorporate selected colors inside the SVG elements." }
          },
          required: ["primaryColor", "secondaryColor", "fontHeading", "fontBody", "letterheadStyle", "logoSvg"]
        }
      }
    });

    const result = JSON.parse(response.text || "{}");

    // Standard fallback design if JSON parse or fields are empty
    const branding: BrandingDetails = {
      theme: themePreference,
      primaryColor: result.primaryColor || "#0f172a",
      secondaryColor: result.secondaryColor || "#3b82f6",
      fontHeading: result.fontHeading || (themePreference === 'Editorial Serif' ? 'Playfair Display' : 'Inter'),
      fontBody: result.fontBody || 'Inter',
      letterheadStyle: (result.letterheadStyle as any) || "Minimal Header",
      logoSvg: result.logoSvg || `<svg width="160" height="48" viewBox="0 0 160 48" fill="none" xmlns="http://www.w3.org/2000/svg"><rect x="10" y="10" width="28" height="28" rx="6" fill="#0f172a"/><circle cx="24" cy="24" r="8" fill="#3b82f6"/><text x="48" y="29" fill="#0f172a" font-family="sans-serif" font-weight="700" font-size="16">${company.name.slice(0, 10)}</text></svg>`
    };

    logs.push({
      id: `log-b2`,
      timestamp: new Date().toISOString(),
      agent: 'Corporate Branding',
      level: 'success',
      message: `Generated corporate identity & logo successfully!`,
      details: `Colors: Primary ${branding.primaryColor}, Secondary ${branding.secondaryColor}. Styling applied: "${branding.letterheadStyle}". Created premium vector SVG logo element.`
    });

    return { branding, logs };
  } catch (err: any) {
    const fallbackBranding: BrandingDetails = {
      theme: themePreference,
      primaryColor: themePreference === 'Coastal Clean' ? '#0d9488' : '#1e293b',
      secondaryColor: '#64748b',
      fontHeading: 'Inter',
      fontBody: 'Inter',
      letterheadStyle: 'Minimal Header',
      logoSvg: `<svg width="160" height="48" viewBox="0 0 160 48" xmlns="http://www.w3.org/2000/svg"><circle cx="24" cy="24" r="14" fill="#1e293b"/><text x="46" y="29" fill="#1e293b" font-family="sans-serif" font-weight="bold" font-size="16">${company.name}</text></svg>`
    };

    logs.push({
      id: `log-b-err`,
      timestamp: new Date().toISOString(),
      agent: 'Corporate Branding',
      level: 'warning',
      message: `Identity designed with local brand template due to API rate limit or fallback.`,
      details: err.message || `${err}`
    });

    return { branding: fallbackBranding, logs };
  }
}

